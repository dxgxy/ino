import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
const compile=spawnSync(process.execPath,['node_modules/typescript/bin/tsc','--ignoreConfig','--target','es2022','--module','esnext','--moduleResolution','bundler','--skipLibCheck','--outDir','output/review-check','src/services/review.ts'],{stdio:'inherit'});
assert.equal(compile.status,0);
const {currentRecord,finishScheme,recordFor,decayLongMark,pendingCards,stabilityDays,normalizeSpelling}=await import('../output/review-check/services/review.js');
const settings={initialLong:0,shortTarget:3,dailyLimit:20,longRemoveAt:7};
const now=new Date(2026,9,25,12); const tomorrow=new Date(2026,9,26,12);
let records=finishScheme([],'l1','w','meaning',false,settings,now);
assert.equal(recordFor(records,'w','l1').shortMark,0);
records=finishScheme(records,'l1','w','meaning',true,settings,now);
assert.equal(recordFor(records,'w','l1').shortMark,1);
records=finishScheme(records,'l1','w','listening',true,settings,now);
assert.equal(recordFor(records,'w','l1').longMark,1);
assert.deepEqual(finishScheme(records,'l1','w','spelling',true,settings,now),records,'Once per day');
assert.equal(currentRecord(records,'w','l2',settings,now).longMark,0,'List isolation');
assert.equal(currentRecord(records,'w','l1',settings,tomorrow).shortMark,1,'Daily A begins at B');
assert.equal(currentRecord(records,'w','l1',settings,tomorrow).attemptsToday,0);
const initial=currentRecord([],'w','l1',{...settings,initialLong:2},now);assert.equal(initial.shortMark,2);assert.equal(initial.longMark,2);
const anchor={...initial,longDecayAt:now.toISOString(),longMark:5};
assert.equal(decayLongMark(anchor,new Date(now.getTime()+(stabilityDays(5)-.01)*86400000)).longMark,5);
assert.equal(decayLongMark(anchor,new Date(now.getTime()+stabilityDays(5)*86400000)).longMark,4);
assert.equal(decayLongMark(anchor,new Date(now.getTime()+(stabilityDays(5)+stabilityDays(4))*86400000)).longMark,3);
assert.equal(decayLongMark(anchor,new Date(now.getTime()+200*86400000)).longMark,0);
const limited={...settings,dailyLimit:1};let failed=finishScheme([],'l1','w','spelling',false,limited,now);assert.equal(pendingCards([{id:'w'}],failed,'l1',limited,now).length,0);assert.equal(finishScheme(failed,'l1','w','spelling',true,limited,now),failed);
assert.equal(recordFor(finishScheme([],'l1','w','spelling',true,settings,now),'w','l1').shortMark,3);
assert.equal(recordFor(finishScheme([],'l1','w','translation',true,settings,now),'w','l1').shortMark,2);
console.log('PASS: four modes, success gating, daily cap/reset, list isolation, decay boundaries, daily promotion and new-card defaults');

assert.equal(normalizeSpelling('  New   York '), 'new york');
let progressing=[];for(let day=0;day<7;day++){progressing=finishScheme(progressing,'p','word','spelling',true,settings,new Date(2026,9,25+day,12));}assert.equal(recordFor(progressing,'word','p').longMark,7,'Daily practice reaches graduation');
